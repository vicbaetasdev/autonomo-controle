-- 2. Tabelas ------------------------------------------------------------------------------

CREATE TABLE servicos (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome         VARCHAR2(80)  NOT NULL,
  preco        NUMBER(10,2)  NOT NULL CHECK (preco >= 0),
  duracao_min  NUMBER(4)     NOT NULL CHECK (duracao_min > 0)
);

CREATE TABLE clientes (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome        VARCHAR2(120) NOT NULL,
  telefone    VARCHAR2(30),
  cor         VARCHAR2(7),
  observacao  VARCHAR2(400),
  criado_em   DATE DEFAULT ON NULL SYSDATE
);

CREATE TABLE atendimentos (
  id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  data_atendimento  DATE          NOT NULL,
  hora              VARCHAR2(5)   NOT NULL CHECK (REGEXP_LIKE(hora, '^[0-2][0-9]:[0-5][0-9]$')),
  cliente_id        NUMBER        NOT NULL REFERENCES clientes (id),
  servico_id        NUMBER        NOT NULL REFERENCES servicos (id),
  duracao_min       NUMBER(4)     NOT NULL CHECK (duracao_min > 0),
  valor             NUMBER(10,2)  NOT NULL CHECK (valor >= 0),
  status            VARCHAR2(12)  DEFAULT ON NULL 'agendado'
                    CHECK (status IN ('agendado', 'confirmado', 'concluido', 'cancelado')),
  forma_pagamento   VARCHAR2(20),
  observacao        VARCHAR2(400)
);
CREATE INDEX atendimentos_data_ix ON atendimentos (data_atendimento);
CREATE INDEX atendimentos_cliente_ix ON atendimentos (cliente_id);

-- tipo: entrada (atendimento concluido) ou saida (despesa)
-- atendimento_id liga a entrada ao atendimento que a gerou; o indice unico impede
-- que o mesmo atendimento lance duas entradas
CREATE TABLE lancamentos (
  id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  data_lancamento  DATE          NOT NULL,
  tipo             VARCHAR2(7)   NOT NULL CHECK (tipo IN ('entrada', 'saida')),
  descricao        VARCHAR2(120) NOT NULL,
  categoria        VARCHAR2(60)  NOT NULL,
  valor            NUMBER(10,2)  NOT NULL CHECK (valor >= 0),
  forma_pagamento  VARCHAR2(20),
  atendimento_id   NUMBER
);
CREATE INDEX lancamentos_data_ix ON lancamentos (data_lancamento);
CREATE UNIQUE INDEX lancamentos_atendimento_uk ON lancamentos (atendimento_id);

CREATE TABLE metas (
  id                 NUMBER       PRIMARY KEY,
  meta_faturamento   NUMBER(12,2) NOT NULL,
  meta_atendimentos  NUMBER(5)    NOT NULL
);

CREATE TABLE tarefas (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  descricao  VARCHAR2(200) NOT NULL,
  concluida  NUMBER(1) DEFAULT ON NULL 0 CHECK (concluida IN (0, 1))
);


-- 3. Regra de negocio: concluir o atendimento lanca a entrada no financeiro --------------
-- Concluiu: cria (ou atualiza) a entrada ligada ao atendimento.
-- Deixou de estar concluido, ou foi apagado: remove a entrada.
-- A regra mora no banco, entao vale para qualquer tela ou integracao que gravar ali.

CREATE OR REPLACE TRIGGER atendimentos_financeiro_trg
AFTER INSERT OR UPDATE OR DELETE ON atendimentos
FOR EACH ROW
DECLARE
  v_cliente  clientes.nome%TYPE;
  v_servico  servicos.nome%TYPE;
BEGIN
  IF DELETING THEN
    DELETE FROM lancamentos WHERE atendimento_id = :old.id;
  ELSIF :new.status = 'concluido' THEN
    SELECT nome INTO v_cliente FROM clientes WHERE id = :new.cliente_id;
    SELECT nome INTO v_servico FROM servicos WHERE id = :new.servico_id;
    UPDATE lancamentos
       SET data_lancamento = :new.data_atendimento,
           descricao       = v_cliente,
           categoria       = v_servico,
           valor           = :new.valor,
           forma_pagamento = :new.forma_pagamento
     WHERE atendimento_id = :new.id;
    IF SQL%ROWCOUNT = 0 THEN
      INSERT INTO lancamentos (data_lancamento, tipo, descricao, categoria, valor,
                               forma_pagamento, atendimento_id)
      VALUES (:new.data_atendimento, 'entrada', v_cliente, v_servico, :new.valor,
              :new.forma_pagamento, :new.id);
    END IF;
  ELSE
    DELETE FROM lancamentos WHERE atendimento_id = :new.id;
  END IF;
END;
/


-- 4. Dados de demonstracao ----------------------------------------------------------------
-- Manicure ficticia (Mariana), historico de 10 semanas ate hoje e 4 dias de agenda a frente.
-- Sempre relativos a data de hoje em Brasilia, para os paineis nunca aparecerem vazios.
-- A semente fixa faz o mesmo dia gerar sempre os mesmos dados.

CREATE OR REPLACE PACKAGE autonomiza_demo AS
  FUNCTION hoje RETURN DATE;
  PROCEDURE reiniciar;
END autonomiza_demo;
/

CREATE OR REPLACE PACKAGE BODY autonomiza_demo AS

  TYPE t_txt IS TABLE OF VARCHAR2(200) INDEX BY PLS_INTEGER;
  TYPE t_num IS TABLE OF NUMBER INDEX BY PLS_INTEGER;

  FUNCTION hoje RETURN DATE IS
  BEGIN
    RETURN TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'America/Sao_Paulo' AS DATE));
  END hoje;

  PROCEDURE reiniciar IS
    v_hoje       DATE := hoje;
    v_dia        DATE;
    v_dow        VARCHAR2(3);
    v_qtd        PLS_INTEGER;
    v_pool       PLS_INTEGER;
    v_status     VARCHAR2(12);
    v_tmp        VARCHAR2(200);
    v_j          PLS_INTEGER;
    horas        t_txt;
    sorteadas    t_txt;
    pagamentos   t_txt;
    svc_ids      t_num;
    svc_preco    t_num;
    svc_dur      t_num;
    cli_ids      t_num;

    FUNCTION rnd RETURN NUMBER IS
    BEGIN
      RETURN DBMS_RANDOM.VALUE;
    END rnd;

    FUNCTION dia_semana(p_dia DATE) RETURN VARCHAR2 IS
    BEGIN
      RETURN TO_CHAR(p_dia, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH');
    END dia_semana;

    PROCEDURE novo_servico(p_nome VARCHAR2, p_preco NUMBER, p_dur NUMBER) IS
      v_id NUMBER;
    BEGIN
      INSERT INTO servicos (nome, preco, duracao_min)
      VALUES (p_nome, p_preco, p_dur)
      RETURNING id INTO v_id;
      svc_ids(svc_ids.COUNT + 1) := v_id;
      svc_preco(svc_preco.COUNT + 1) := p_preco;
      svc_dur(svc_dur.COUNT + 1) := p_dur;
    END novo_servico;

    PROCEDURE novo_cliente(p_nome VARCHAR2, p_tel VARCHAR2, p_cor VARCHAR2, p_obs VARCHAR2) IS
      v_id NUMBER;
    BEGIN
      INSERT INTO clientes (nome, telefone, cor, observacao)
      VALUES (p_nome, p_tel, p_cor, p_obs)
      RETURNING id INTO v_id;
      cli_ids(cli_ids.COUNT + 1) := v_id;
    END novo_cliente;

    PROCEDURE novo_atendimento(p_dia DATE, p_hora VARCHAR2, p_cli PLS_INTEGER,
                               p_svc PLS_INTEGER, p_status VARCHAR2) IS
      v_cli_id  NUMBER := cli_ids(p_cli);
      v_svc_id  NUMBER := svc_ids(p_svc);
      v_dur     NUMBER := svc_dur(p_svc);
      v_valor   NUMBER := svc_preco(p_svc);
      v_pag     VARCHAR2(20) := pagamentos(1 + TRUNC(rnd * pagamentos.COUNT));
    BEGIN
      INSERT INTO atendimentos (data_atendimento, hora, cliente_id, servico_id,
                                duracao_min, valor, status, forma_pagamento)
      VALUES (p_dia, p_hora, v_cli_id, v_svc_id, v_dur, v_valor, p_status, v_pag);
    END novo_atendimento;

    PROCEDURE nova_saida(p_dia DATE, p_desc VARCHAR2, p_cat VARCHAR2,
                         p_valor NUMBER, p_pag VARCHAR2) IS
    BEGIN
      INSERT INTO lancamentos (data_lancamento, tipo, descricao, categoria, valor, forma_pagamento)
      VALUES (p_dia, 'saida', p_desc, p_cat, p_valor, p_pag);
    END nova_saida;

    -- sorteia p_qtd horarios diferentes da grade do dia
    PROCEDURE sortear_horas(p_qtd PLS_INTEGER) IS
    BEGIN
      sorteadas := horas;
      FOR i IN REVERSE 2 .. sorteadas.COUNT LOOP
        v_j := 1 + TRUNC(rnd * i);
        v_tmp := sorteadas(i);
        sorteadas(i) := sorteadas(v_j);
        sorteadas(v_j) := v_tmp;
      END LOOP;
      FOR i IN REVERSE p_qtd + 1 .. sorteadas.COUNT LOOP
        sorteadas.DELETE(i);
      END LOOP;
    END sortear_horas;

  BEGIN
    DBMS_RANDOM.SEED(20260922);

    DELETE FROM atendimentos;
    DELETE FROM lancamentos;
    DELETE FROM tarefas;
    DELETE FROM metas;
    DELETE FROM clientes;
    DELETE FROM servicos;

    horas(1) := '09:00'; horas(2) := '10:30'; horas(3) := '11:00'; horas(4) := '13:00';
    horas(5) := '14:00'; horas(6) := '15:30'; horas(7) := '16:00'; horas(8) := '17:00';

    pagamentos(1) := 'Pix'; pagamentos(2) := 'Pix'; pagamentos(3) := 'Pix';
    pagamentos(4) := 'Dinheiro'; pagamentos(5) := 'Crédito'; pagamentos(6) := 'Débito';

    novo_servico('Manicure',          30,  45);
    novo_servico('Alongamento',       120, 120);
    novo_servico('Esmaltação em gel', 50,  60);
    novo_servico('Manutenção',        60,  75);
    novo_servico('Spa dos pés',       45,  40);

    novo_cliente('Maria Silva',    '(91) 98000-1000', '#8B5CF6', 'Prefere tons nude, alergia a acetona pura.');
    novo_cliente('Ana Paula',      '(91) 98111-1077', '#22D3EE', NULL);
    novo_cliente('Beatriz Lima',   '(91) 98222-1154', '#FBBF24', NULL);
    novo_cliente('Camila Santos',  '(91) 98333-1231', '#34D399', NULL);
    novo_cliente('Juliana Costa',  '(91) 98444-1308', '#FB7185', NULL);
    novo_cliente('Pedro Santos',   '(91) 98555-1385', '#6366F1', NULL);
    novo_cliente('Renata Lima',    '(91) 98666-1462', '#22D3EE', NULL);
    novo_cliente('Carla Menezes',  '(91) 98777-1539', '#8B5CF6', NULL);
    novo_cliente('Fernanda Dias',  '(91) 98888-1616', '#34D399', NULL);
    novo_cliente('Patrícia Rocha', '(91) 98999-1693', '#FBBF24', NULL);

    -- historico: ultimas 10 semanas, terca a sabado; quarta de proposito mais vazia
    FOR dias_atras IN REVERSE 0 .. 70 LOOP
      v_dia := v_hoje - dias_atras;
      v_dow := dia_semana(v_dia);
      IF v_dow NOT IN ('SUN', 'MON') THEN
        IF v_dow = 'WED' THEN
          v_qtd := CASE WHEN rnd < 0.5 THEN 1 ELSE 2 END;
        ELSE
          -- mes atual um pouco mais cheio: o negocio esta crescendo
          v_qtd := 3 + CASE WHEN dias_atras <= 25 THEN 1 ELSE 0 END + TRUNC(rnd * 3);
        END IF;
        sortear_horas(v_qtd);
        -- as duas ultimas clientes so aparecem nas ultimas semanas (clientes novas)
        v_pool := CASE WHEN dias_atras > 21 THEN cli_ids.COUNT - 2 ELSE cli_ids.COUNT END;
        FOR h IN 1 .. sorteadas.COUNT LOOP
          IF dias_atras > 0 THEN
            v_status := CASE WHEN rnd < 0.9 THEN 'concluido' ELSE 'cancelado' END;
          ELSE
            v_status := CASE WHEN rnd < 0.6 THEN 'confirmado' ELSE 'agendado' END;
          END IF;
          novo_atendimento(v_dia, sorteadas(h), 1 + TRUNC(rnd * v_pool),
                           1 + TRUNC(rnd * svc_ids.COUNT), v_status);
        END LOOP;
        IF dias_atras > 0 AND v_dow = 'SAT' AND rnd < 0.9 THEN
          nova_saida(v_dia, 'Esmaltes e materiais', 'Material de trabalho', 60 + TRUNC(rnd * 70), 'Pix');
        END IF;
        IF dias_atras > 0 AND rnd < 0.18 THEN
          nova_saida(v_dia, 'Uber até a cliente', 'Transporte', 18 + TRUNC(rnd * 30), 'Pix');
        END IF;
      END IF;
    END LOOP;

    -- proximos dias ja com horario marcado
    FOR dias_frente IN 1 .. 4 LOOP
      v_dia := v_hoje + dias_frente;
      v_dow := dia_semana(v_dia);
      IF v_dow NOT IN ('SUN', 'MON') THEN
        sortear_horas(CASE WHEN v_dow = 'WED' THEN 1 ELSE 3 END);
        FOR h IN 1 .. sorteadas.COUNT LOOP
          novo_atendimento(v_dia, sorteadas(h), 1 + TRUNC(rnd * cli_ids.COUNT),
                           1 + TRUNC(rnd * svc_ids.COUNT),
                           CASE WHEN rnd < 0.5 THEN 'confirmado' ELSE 'agendado' END);
        END LOOP;
      END IF;
    END LOOP;

    -- despesas fixas do mes atual e do anterior
    FOR meses_atras IN 0 .. 1 LOOP
      v_dia := ADD_MONTHS(TRUNC(v_hoje, 'MM'), -meses_atras) + 4;
      IF v_dia <= v_hoje THEN
        nova_saida(v_dia, 'Aluguel do espaço', 'Aluguel do espaço', 550, 'Pix');
      END IF;
    END LOOP;
    nova_saida(v_hoje, 'Outros gastos do mês', 'Outros', 48 + TRUNC(rnd * 40), 'Dinheiro');

    INSERT INTO metas (id, meta_faturamento, meta_atendimentos) VALUES (1, 6000, 75);

    INSERT INTO tarefas (descricao, concluida) VALUES ('Confirmar agenda de amanhã', 1);
    INSERT INTO tarefas (descricao, concluida) VALUES ('Comprar esmaltes em gel', 1);
    INSERT INTO tarefas (descricao, concluida) VALUES ('Responder orçamento da Beatriz', 0);
    INSERT INTO tarefas (descricao, concluida) VALUES ('Postar fotos do alongamento', 0);
    INSERT INTO tarefas (descricao, concluida) VALUES ('Separar recibos do mês', 0);

    COMMIT;
  END reiniciar;

END autonomiza_demo;
/


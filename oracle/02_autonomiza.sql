-- 6. API REST (ORDS) ----------------------------------------------------------------------
-- REST automatico das tabelas: GET, POST, PUT e DELETE em .../ords/autonomiza/<tabela>/

BEGIN
  FOR t IN (SELECT 'SERVICOS' AS obj, 'servicos' AS alias FROM dual
            UNION ALL SELECT 'CLIENTES', 'clientes' FROM dual
            UNION ALL SELECT 'ATENDIMENTOS', 'atendimentos' FROM dual
            UNION ALL SELECT 'LANCAMENTOS', 'lancamentos' FROM dual
            UNION ALL SELECT 'METAS', 'metas' FROM dual
            UNION ALL SELECT 'TAREFAS', 'tarefas' FROM dual) LOOP
    ORDS.ENABLE_OBJECT(
      p_enabled        => TRUE,
      p_schema         => USER,
      p_object         => t.obj,
      p_object_type    => 'TABLE',
      p_object_alias   => t.alias,
      p_auto_rest_auth => FALSE);
  END LOOP;
  COMMIT;
END;
/

-- Rotas do app: saude, indicadores calculados no banco e reinicio dos dados de demonstracao
--   GET  .../ords/autonomiza/app/saude
--   GET  .../ords/autonomiza/app/resumo
--   POST .../ords/autonomiza/app/demo/reiniciar
BEGIN
  ORDS.DEFINE_MODULE(
    p_module_name    => 'autonomiza.app',
    p_base_path      => '/app/',
    p_items_per_page => 25,
    p_status         => 'PUBLISHED',
    p_comments       => 'Rotas do app Autonomiza');

  ORDS.DEFINE_TEMPLATE(p_module_name => 'autonomiza.app', p_pattern => 'saude');
  ORDS.DEFINE_HANDLER(
    p_module_name => 'autonomiza.app',
    p_pattern     => 'saude',
    p_method      => 'GET',
    p_source_type => ORDS.source_type_query_one_row,
    p_source      => q'[
      SELECT 'ok' AS status,
             TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'America/Sao_Paulo',
                     'YYYY-MM-DD"T"HH24:MI:SS') AS agora,
             (SELECT COUNT(*) FROM atendimentos) AS atendimentos,
             (SELECT COUNT(*) FROM lancamentos) AS lancamentos
        FROM dual]');

  ORDS.DEFINE_TEMPLATE(p_module_name => 'autonomiza.app', p_pattern => 'resumo');
  ORDS.DEFINE_HANDLER(
    p_module_name => 'autonomiza.app',
    p_pattern     => 'resumo',
    p_method      => 'GET',
    p_source_type => ORDS.source_type_query_one_row,
    p_source      => q'[
      SELECT f.faturamento_mes,
             f.vendas_mes,
             ROUND(f.faturamento_mes / NULLIF(f.vendas_mes, 0), 2) AS ticket_medio,
             c.taxa_cancelamento_30d,
             o.dia_mais_vazio
        FROM (SELECT NVL(SUM(valor), 0) AS faturamento_mes, COUNT(*) AS vendas_mes
                FROM lancamentos
               WHERE tipo = 'entrada'
                 AND data_lancamento >= TRUNC(autonomiza_demo.hoje, 'MM')) f,
             (SELECT ROUND(100 * COUNT(CASE WHEN status = 'cancelado' THEN 1 END)
                     / NULLIF(COUNT(*), 0), 1) AS taxa_cancelamento_30d
                FROM atendimentos
               WHERE data_atendimento BETWEEN autonomiza_demo.hoje - 30
                                          AND autonomiza_demo.hoje - 1) c,
             (SELECT MIN(dia) KEEP (DENSE_RANK FIRST ORDER BY qtd) AS dia_mais_vazio
                FROM (SELECT TO_CHAR(data_atendimento, 'fmDay',
                                     'NLS_DATE_LANGUAGE=''BRAZILIAN PORTUGUESE''') AS dia,
                             COUNT(*) AS qtd
                        FROM atendimentos
                       WHERE status <> 'cancelado'
                         AND data_atendimento BETWEEN autonomiza_demo.hoje - 56
                                                  AND autonomiza_demo.hoje - 1
                         AND TO_CHAR(data_atendimento, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH')
                             NOT IN ('SUN', 'MON')
                       GROUP BY TO_CHAR(data_atendimento, 'fmDay',
                                        'NLS_DATE_LANGUAGE=''BRAZILIAN PORTUGUESE'''))) o]');

  ORDS.DEFINE_TEMPLATE(p_module_name => 'autonomiza.app', p_pattern => 'demo/reiniciar');
  ORDS.DEFINE_HANDLER(
    p_module_name => 'autonomiza.app',
    p_pattern     => 'demo/reiniciar',
    p_method      => 'POST',
    p_source_type => ORDS.source_type_plsql,
    p_source      => q'[
      BEGIN
        autonomiza_demo.reiniciar;
        owa_util.mime_header('application/json', TRUE);
        htp.p('{"ok":true}');
      END;]');

  COMMIT;
END;

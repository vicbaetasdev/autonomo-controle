-- 7. Conferencia: deve listar 5 servicos, 10 clientes, centenas de atendimentos e lancamentos,
--    1 meta e 5 tarefas
SELECT 'servicos' AS tabela, COUNT(*) AS linhas FROM servicos
UNION ALL SELECT 'clientes', COUNT(*) FROM clientes
UNION ALL SELECT 'atendimentos', COUNT(*) FROM atendimentos
UNION ALL SELECT 'lancamentos', COUNT(*) FROM lancamentos
UNION ALL SELECT 'metas', COUNT(*) FROM metas
UNION ALL SELECT 'tarefas', COUNT(*) FROM tarefas;
